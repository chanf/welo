ALTER TABLE users ADD COLUMN color TEXT NOT NULL DEFAULT '#2563EB';

UPDATE users
SET color = CASE (id - 1) % 12
  WHEN 0 THEN '#2563EB'
  WHEN 1 THEN '#DC2626'
  WHEN 2 THEN '#059669'
  WHEN 3 THEN '#D97706'
  WHEN 4 THEN '#7C3AED'
  WHEN 5 THEN '#0891B2'
  WHEN 6 THEN '#DB2777'
  WHEN 7 THEN '#65A30D'
  WHEN 8 THEN '#EA580C'
  WHEN 9 THEN '#0F766E'
  WHEN 10 THEN '#9333EA'
  ELSE '#BE123C'
END;
